/**
 * Livo-Übungsfragen.
 *
 * Alle Fragen sind eigenständig formuliert (kein Abdruck des amtlichen
 * Fragenkatalogs) und orientieren sich an den Regeln der StVO, StVG, FeV und
 * StVZO. Punkte und die Einteilung in Grundstoff (G) und Zusatzstoff Klasse B
 * (B) bilden den Aufbau der echten Theorieprüfung nach.
 */
import type { CategoryId, ChoiceQuestion, NumberQuestion, Points, Pool, Question, SignId } from './types';

const IDS = ['a', 'b', 'c', 'd', 'e'];

function choice(
  id: string,
  category: CategoryId,
  pool: Pool,
  points: Points,
  text: string,
  options: [string, boolean][],
  explanation: string,
  sign?: SignId,
): ChoiceQuestion {
  return {
    id,
    type: 'choice',
    category,
    pool,
    points,
    text,
    sign,
    explanation,
    options: options.map(([t], i) => ({ id: IDS[i], text: t })),
    correct: options.flatMap(([, ok], i) => (ok ? [IDS[i]] : [])),
  };
}

function number(
  id: string,
  category: CategoryId,
  pool: Pool,
  points: Points,
  text: string,
  answer: number,
  unit: string,
  explanation: string,
  sign?: SignId,
): NumberQuestion {
  return { id, type: 'number', category, pool, points, text, answer, unit, explanation, sign };
}

